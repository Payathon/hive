import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

// Where delivered files' bytes live. Metadata is in the `files` table; swap this for object storage later.
export interface FileStore {
  put(id: string, bytes: Uint8Array): Promise<void>;
  get(id: string): Promise<Uint8Array | null>;
}

export class DiskFileStore implements FileStore {
  constructor(private readonly root: string) {}

  async put(id: string, bytes: Uint8Array) {
    await mkdir(this.root, { recursive: true });
    await writeFile(this.path(id), bytes);
  }

  async get(id: string) {
    try {
      return new Uint8Array(await readFile(this.path(id)));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw err;
    }
  }

  // Ids are generated by hive, but keep them from naming anything outside the root regardless.
  private path(id: string) {
    if (!/^[\w-]+$/.test(id)) throw new Error(`bad file id ${id}`);
    return join(this.root, id);
  }
}

// For tests and throwaway runs.
export class MemoryFileStore implements FileStore {
  private readonly files = new Map<string, Uint8Array>();
  async put(id: string, bytes: Uint8Array) {
    this.files.set(id, bytes);
  }
  async get(id: string) {
    return this.files.get(id) ?? null;
  }
}
